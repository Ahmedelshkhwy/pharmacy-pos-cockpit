def test_profit_loss_explains_drivers_with_items(tmp_path):
    pl = run([SAMPLES / "A_arabic_pharmacy_report.xlsx"], tmp_path).branches[0].summary["profit_loss"]
    keys = {driver["key"]: driver for driver in pl["drivers"]}
    assert {"stockout", "expiry", "negative_margin", "dead_stock", "overstock"} <= set(keys)
    assert pl["total_loss"] == pytest.approx(sum(d["amount"] for d in pl["drivers"] if d["kind"] == "loss"))
    assert all(driver["top_items"] for driver in pl["drivers"])
    assert {item["name"] for item in keys["negative_margin"]["top_items"]} == generate_samples.below_cost_names(generate_samples.build_branch(11, "A"))
    assert pl["headline_ar"] and pl["profit_sources"]["pareto_count"] > 0


def test_missing_cost_is_reported_not_guessed(tmp_path):
    path = tmp_path / "sales.csv"
    path.write_text("Date,Item,Qty,Price\n01/10/2026,Panadol,2,40\n03/10/2026,Brufen,1,25\n", encoding="utf-8")
    pl = run([path], tmp_path / "out").branches[0].summary["profit_loss"]
    assert "no_cost" in pl["warnings"] and "no_stock" in pl["warnings"]
    assert pl["gross_profit"] == 0 and pl["profit_sources"]["basis"] == "revenue"
