def test_sales_without_period_requires_user_input(tmp_path):
    path = tmp_path / "plain.csv"
    path.write_text("Item,Sold,Stock,Cost,Price\nPanadol,10,5,30,40\nBrufen,0,8,20,25\n", encoding="utf-8")
    with pytest.raises(ValueError, match="period_required"):
        run([path], tmp_path / "out")
    result = run([path], tmp_path / "out", period=30)
    assert result.branches[0].summary["metadata"]["period_source"] == "user"


def test_duplicate_invoice_lines_are_removed(tmp_path):
    path = tmp_path / "sales.csv"
    path.write_text(
        "Date,Invoice,Code,Item,Qty,Price\n"
        "01/10/2026,1,P1,Panadol,2,40\n"
        "01/10/2026,1,P1,Panadol,2,40\n"
        "05/10/2026,2,P1,Panadol,-1,40\n",
        encoding="utf-8",
    )
    result = run([path], tmp_path / "out")
    assert result.quality["counters"]["duplicate_transaction"] == 1
    row = next(csv.DictReader((result.branches[0].output_dir / "merged_items.csv").open(encoding="utf-8-sig")))
    assert float(row["pos_sales"]) == 1 and float(row["returns_qty"]) == 1


def test_fefo_expiry_risk_sells_oldest_batch_first():
    # 1 unit/day; 50 units expiring in 20 days -> 30 at risk; the later batch has time to sell.
    expired, at_risk, nearest, days_left = fefo_expiry_risk(
        {"2026-11-20": 50, "2027-06-30": 10, "2026-10-01": 4}, avg_daily_sales=1.0, today=TODAY
    )
    assert expired == 4
    assert at_risk == 30
    assert nearest == "2026-10-01" and days_left == -30


