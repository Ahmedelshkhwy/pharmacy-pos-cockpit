# --- end-to-end against ground truth ------------------------------------------------------

def test_arabic_report_matches_ground_truth(tmp_path):
    result = run([SAMPLES / "A_arabic_pharmacy_report.xlsx"], tmp_path)
    assert [b.branch for b in result.branches] == ["المعادي"]
    counters = result.quality["counters"]
    assert counters["totals_row"] == 1 and counters["repeated_header"] == 1 and counters["negative_stock"] == 1
    assert "bad_number" not in counters

    rows = {row["ref"]: row for row in csv.DictReader((result.branches[0].output_dir / "merged_items.csv").open(encoding="utf-8-sig"))}
    for item in generate_samples.build_branch(11, "A"):
        row = rows[item.code]
        assert float(row["pos_sales"]) == item.sold_qty
        assert float(row["qoh"]) == item.stock
        assert float(row["net_sales"]) == pytest.approx(item.sales_value, abs=0.01)
        assert float(row["cost"]) == pytest.approx(item.cost, abs=0.01)
        assert float(row["gross_profit"]) == pytest.approx(item.sales_value - item.sold_qty * item.cost, abs=0.05)


def test_invoices_and_batches_merge_by_barcode(tmp_path):
    result = run([SAMPLES / "B_sales_invoices.csv", SAMPLES / "B_stock_batches.csv"], tmp_path, branch="Heliopolis")
    summary = result.branches[0].summary
    assert summary["metadata"]["period_source"] == "transactions"
    assert summary["metadata"]["period_days"] == "90"

    returns: dict[str, int] = {}
    with (SAMPLES / "B_sales_invoices.csv").open(encoding="cp1256") as handle:
        for line in csv.DictReader(handle, delimiter=";"):
            if int(line["الكمية"]) < 0:
                returns[line["الباركود"]] = returns.get(line["الباركود"], 0) + 1
    rows = {row["barcode"]: row for row in csv.DictReader((result.branches[0].output_dir / "merged_items.csv").open(encoding="utf-8-sig"))}
    assert len(rows) == 80
    for item in generate_samples.build_branch(23, "B"):
        row = rows[item.barcode]
        assert float(row["pos_sales"]) == item.sold_qty - returns.get(item.barcode, 0)
        assert float(row["qoh"]) == item.stock  # batches summed, not double counted


def test_legacy_three_file_export_matches_original_pipeline(tmp_path):
    folder = SAMPLES / "C_legacy_pos"
    smart = run(sorted(folder.glob("*.xlsx")), tmp_path / "smart", branch="i-3").branches[0].summary
    legacy = json.loads((analyze_pos_exports(folder, tmp_path / "legacy", prefix="i-3-", branch_override="i-3") / "summary.json").read_text())
    for key in ["total_items", "total_pos_sales_qty", "total_net_sales", "total_stock_value", "total_cost_value", "lost_sales_value", "frozen_capital_value", "high_risk_count"]:
        assert smart[key] == pytest.approx(legacy[key]), key
    smart_only = {"negative_margin", "expired", "near_expiry", "expiry_risk"}
    assert {tag: n for tag, n in smart["tag_counts"].items() if tag not in smart_only} == legacy["tag_counts"]


